export const t = derived(locale, ($locale) => {
	return (key: string, params?: Record<string, string>): string => {
		let str = translations[$locale]?.[key] ?? translations['en']?.[key] ?? key;
		if (params) {
			for (const [k, v] of Object.entries(params)) {
				str = str.replace(`{${k}}`, v);
			}
		}
		return str;
	};
});
